/**
 * Build the browser client bundle for dsh-appview.
 *
 * Mirrors the reference plugin's build wrapper exactly: esbuild bundles
 * `src/client.jsx` as CJS with React kept external (the browser platform
 * module table provides react / react-dom / react/jsx-runtime), then the output
 * is wrapped in `window.__ModuleLoader__.load({ id, factory })` — the contract
 * `@deepseek-ai/dsh-client-modules` expects for every plugin bundle.
 *
 * Run from the workspace root: node scripts/build.mjs
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { devRequire, devResolve } from './dev-deps.mjs';

const { build } = devRequire('esbuild');
const root = fileURLToPath(new URL('../', import.meta.url));
const packageId = 'dsh-appview';

const { outputFiles } = await build({
  entryPoints: [root + 'src/client.jsx'],
  bundle: true,
  write: false,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  jsx: 'automatic',
  external: ['react', 'react-dom', 'react/jsx-runtime'],
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'inline',
});

await writeFile(
  root + 'lib/client.js',
  '// Generated by node scripts/build.mjs. Edit src/, not this bundle.\n' +
    `window.__ModuleLoader__.load({ id: "${packageId}", factory: (require) => {\n` +
    'var module = { exports: {} }; var exports = module.exports;\n' +
    outputFiles[0].text.replace(/[\t ]+$/gm, '') +
    '\nreturn module.exports;\n} });\n',
);

console.log(`Built ${packageId} client bundle: lib/client.js (${outputFiles[0].text.length} bytes source)`);

// Zod Mini is bundled into the host half; the installed plugin still needs no npm dependencies.
await build({
  entryPoints: [root + 'src/host.js'], outfile: root + 'lib/index.js',
  bundle: true, format: 'esm', platform: 'node', target: 'node20', minify: true,
  banner: { js: '// Generated by scripts/build.mjs. Edit src/host.js.' },
  plugins: [{ name: 'dev-zod', setup(builder) {
    builder.onResolve({ filter: /^zod\/mini$/ }, () => ({ path: devResolve('zod/mini').replace(/\.cjs$/, '.js') }));
  } }],
});
console.log('Built dsh-appview host bundle: lib/index.js');
